    p "    EXT_OUTPUTS(HARNESS_CLEAR_OUTPUT_CHANNEL)"
  )
  ; List.iter (fun (r : io_layout) -> 
    match r.io with
    | Input -> p" auto %s(%s ready);" r.name (r.argtyp_n) 
    | Output -> p "%s %s(%s v);" (r.rettyp_n) r.name (r.argtyp_n)
    | Function -> () 
      ) (io_layouts cout graph)
  ; p "};"

let channel_macros (io: io) () = 
  let (arguments, p_or_s) = ("name, width, storage", "stored_t") in 
  let s_io = match io with 
    | Input -> "input"
    | Output -> "output" 
    | Function -> failwith "should not generate channel macros for functions" in
  p "#define DEF_%s_CHANNEL(%s) \\" (String.uppercase_ascii s_io) arguments; 
  p " %s_channel_fifo<%s::name##_%s> %s::name##_chan;" s_io n_extfuns_impl p_or_s n_extfuns_impl; 
  p "EXT_%sS(DEF_%s_CHANNEL)" (String.uppercase_ascii s_io) (String.uppercase_ascii s_io);
  p "#undef DEF_%s_CHANNEL" (String.uppercase_ascii s_io)

let channel_func(cout : Cpp.cpp_output_t) graph() : unit= 
let io_layout  = io_layouts cout graph in
  List.iter (fun r ->
    match r.io with   
    | Input -> 
                p_fn ~typ:"inline auto" ~name:(n_extfuns_impl^"::"^r.name) ~args:(Printf.sprintf "%s ready" (r.argtyp_n)) (fun () ->
                  p " // ready can be ignored"; 
                  p "  const %s_stored_t p = %s_chan.pop_or_zero();" r.name r.name;
                  p "  return p;" )
    | Output -> p_fn ~typ:(Printf.sprintf "inline %s" (r.rettyp_n)) ~name:(n_extfuns_impl^"::"^r.name) ~args:(Printf.sprintf "%s v" (r.argtyp_n)) (fun () ->
                  p "  %s_chan.push(static_cast<%s_stored_t>(v));" r.name r.name;
                  p "  return bits<1>::mk(true);")
    | Function -> ()
  ) io_layout 

