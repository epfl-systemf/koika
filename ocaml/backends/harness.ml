let contains s1 s2 =
  try
    let len = String.length s2 in
    for i = 0 to String.length s1 - len do
      if String.sub s1 i len = s2 then raise Exit
    done;
    false
  with Exit -> true
  

let internal_by_ffi_name (graph : Cuttlebone.Graphs.circuit_graph) =
  let tbl = Hashtbl.create 16 in
  List.iter
    (fun node ->
      match node.Hashcons.node with
      | Cuttlebone.Graphs.CExternal { f; internal; _ } ->
          Hashtbl.replace tbl f.ffi_name internal
      | _ -> ())
    graph.graph_nodes;
  tbl

let io_layouts (cout : Cpp.cpp_output_t)  (graph: Cuttlebone.Graphs.circuit_graph)  : io_layout list =
  let internal_tbl = internal_by_ffi_name graph in
  let (_final_off, acc_rev) =
    List.fold_left
      (fun (off, acc) ffi ->
         let name = ffi.ffi_name in
          let is_internal =
           match Hashtbl.find_opt internal_tbl name with
           | Some b -> b
           | None -> false
         in
         let io =
           if is_internal then Function
           else if contains name "output" || contains name "out" then Output
           else Input
         in
         let typ = if io = Input then ffi.ffi_rettype else ffi.ffi_argtype in
         let type_n = Cpp.cpp_type_of_type cout.co_program_info typ in
         let rettyp = ffi.ffi_rettype in
         let argtyp = ffi.ffi_argtype in
         let rettyp_n = Cpp.cpp_type_of_type cout.co_program_info rettyp in
         let argtyp_n = Cpp.cpp_type_of_type cout.co_program_info argtyp in
         let bits = typ_sz typ in
         let bytes = (bits + 7) / 8 in
         let entry = { name; io; typ; type_n; rettyp; argtyp; rettyp_n; argtyp_n; bits; bytes; off} in
         let next_off =
           match io with
           | Input -> off + bytes
           | _ -> off
         in
         (next_off, entry :: acc))
      (0, [])
      cout.co_ext_funcs
  in
  List.rev acc_rev



let register_layouts (cu : (_,_,_,_,_,_) Cpp.cpp_input_t) : reg_layout list =
  let (_final_off, acc_rev) =
    Array.fold_left (fun (off, acc) r ->
      let kind = cu.cpp_register_kinds r in
      (* keep your current policy: only Value regs *)
      match kind with
      | Extr.Value ->
          let sg = cu.cpp_register_sigs r in
          let typ = reg_type sg in
          let bits = typ_sz typ in
          let bytes = (bits + 7) / 8 in
          let entry = { name = sg.reg_name; typ; kind; bits; bytes; off } in
          (off + bytes, entry :: acc)
      | _ ->
          (off, acc)
    ) (0, []) cu.cpp_registers
  in
  List.rev acc_rev

  let all_register_layouts (cu : (_,_,_,_,_,_) Cpp.cpp_input_t) : reg_layout list =
  let (_final_off, acc_rev) =
    Array.fold_left (fun (off, acc) r ->
      let sg = cu.cpp_register_sigs r in
      let kind = cu.cpp_register_kinds r in
      let typ = reg_type sg in
      let bits = typ_sz typ in
      let bytes = (bits + 7) / 8 in
      let entry = { name = sg.reg_name; typ; kind; bits; bytes; off } in
      (off + bytes, entry :: acc)
    ) (0, []) cu.cpp_registers
  in
  List.rev acc_rev
let register_kind_to_string kind = 
  match kind with
  | Extr.Value -> "value"
  | Extr.Wire -> "wire"
  | Extr.Register -> "register"
  | Extr.EHR -> "ehr"


let macro_variables (name : string) (registers : 'a list)
    ~(get_name : 'a -> string) ~(get_bits : 'a -> int) () =
  p "#define %s(X) \\" name;
  let rec aux = function
    | [] -> ()
    | [r] -> p "   X(%s, %d)" (get_name r) (get_bits r)
    | r :: rs ->
        p "   X(%s, %d) \\" (get_name r) (get_bits r);
        aux rs
  in
  aux registers


let macro_var_io (name : string) (registers : 'a list)
    ~(get_name : 'a -> string) ~(get_bits : 'a -> int) () =
  p "#define %s(X) \\" name;
  let rec aux = function
    | [] -> ()
    | [r] -> p "   X(%s, %s, %s)" (get_name r) r.argtyp_n r.rettyp_n; (* needs fixing won't generalize*)
    | r :: rs ->
        p "   X(%s, %s,  %s) \\" (get_name r) r.argtyp_n r.rettyp_n;  (* needs fixing won't generalize*)
        aux rs
  in
  aux registers

